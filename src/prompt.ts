function preferenceGuidance(preference: Preference, enabled: readonly ModelRole[]): string {
  if (!hasSmallMedium(enabled)) {
    return `${preference} is inactive because Small or Medium is disabled.`;
  }
  if (preference === "efficient") {
    return "Use efficient only as a Small tie-break when Small and Medium are comparably credible. Do not choose Small when Medium is a materially better task fit.";
  }
  if (preference === "intensive") {
    return "Use intensive only as a Medium tie-break when Small and Medium are comparably credible. Do not choose Medium when Small is the clearly better task fit.";
  }
  return "Standard adds no Small or Medium bias; follow task fit.";
}

function preferencePreview(preference: Preference, enabled: readonly ModelRole[]): string {
  if (!hasSmallMedium(enabled)) return `${preference} inactive (Small or Medium disabled)`;
  if (preference === "efficient") return "efficient breaks comparable fits toward Small";
  if (preference === "intensive") return "intensive breaks comparable fits toward Medium";
  return "standard has no extra bias";
}

function promptString(value: string): string {
  return JSON.stringify(value)
    .replaceAll("<", "\\u003c")
    .replaceAll(">", "\\u003e")
    .replaceAll("&", "\\u0026");
}

function formatLaunchModel(reference: ModelRef): string {
  return promptString(`${reference.provider}/${reference.model}`);
}

type RoleThinking =
  | { kind: "fixed"; level: string }
  | { kind: "range"; min: string; max: string }
  | { kind: "unset" };

function roleThinking(policy: ThinkingPolicy | undefined): RoleThinking {
  if (!policy) return { kind: "unset" };
  return "level" in policy
    ? { kind: "fixed", level: policy.level }
    : { kind: "range", min: policy.min, max: policy.max };
}

/** Fixed policies show the literal level; range and unset keep the `:LEVEL` placeholder. */
function formatThinkingLaunchModel(reference: ModelRef, thinking: RoleThinking): string {
  const base = `${reference.provider}/${reference.model}`;
  return promptString(thinking.kind === "fixed" ? `${base}:${thinking.level}` : `${base}:LEVEL`);
}

function thinkingPolicyText(thinking: RoleThinking): string {
  if (thinking.kind === "fixed") return `fixed ${thinking.level} (must not change)`;
  if (thinking.kind === "range")
    return `range ${thinking.min}..${thinking.max} inclusive (choose within it)`;
  return "unset (choose per run)";
}

function thinkingPreviewToken(thinking: RoleThinking): string {
  if (thinking.kind === "fixed") return `:${thinking.level}`;
  if (thinking.kind === "range") return `:${thinking.min}..${thinking.max}`;
  return ":per-run";
}

function roleName(role: ModelRole): string {
  return role[0]!.toUpperCase() + role.slice(1);
}

/** One mechanical line per enabled role: the base a launch carries and the level it may carry. */
function roleLine(label: string, reference: ModelRef, thinking: RoleThinking, detail = ""): string {
  return `- ${label}: exact model base: ${formatLaunchModel(reference)}; pi-subagents form: ${formatThinkingLaunchModel(reference, thinking)}; thinking: ${thinkingPolicyText(thinking)}${detail}.`;
}

function rolesByState(effective: EffectiveDelegateState): {
  enabled: ModelRole[];
  disabled: ModelRole[];
  unconfigured: ModelRole[];
} {
  return {
    enabled: enabledOrdinaryRoles(effective),
    disabled: (["small", "medium", "large"] as const).filter((role) =>
      isRoleDisabled(effective[role]),
    ),
    unconfigured: (["small", "medium", "large"] as const).filter(
      (role) => effective[role] === undefined,
    ),
  };
}

export function buildPolicyPreview(
  effective: EffectiveDelegateState,
  validAdvisorCount?: number,
): string[] {
  if (effective.intensity === "off") {
    if (!isAdvisorEnabled(effective)) return ["off · no policy injected"];
    return [
      "Delegation off · Advisor on · consultation only",
      validAdvisorCount === undefined
        ? `${effective.advisors.length} Advisor models configured · validation pending`
        : `${validAdvisorCount} of ${effective.advisors.length} advisors valid${validAdvisorCount === 0 ? " · no policy can be injected" : ""}`,
    ];
  }

  const { enabled, disabled, unconfigured } = rolesByState(effective);
  if (unconfigured.length > 0) {
    return [`active · ${roleName(unconfigured[0]!)} not configured · no policy can be injected`];
  }
  if (enabled.length === 0)
    return ["active · no ordinary role enabled · no policy can be injected"];

  const references = enabled
    .map(
      (role) =>
        `${roleName(role)} ${formatLaunchModel(effective[role] as ModelRef)}${thinkingPreviewToken(roleThinking(effective.thinking[role]))}`,
    )
    .join(" · ");
  return [
    `${effective.intensity} · task fit first · ${preferencePreview(effective.preference, enabled)}`,
    `Enabled: ${enabled.map(roleName).join(", ")}${disabled.length ? ` · Disabled: ${disabled.map(roleName).join(", ")}` : ""}`,
    `${references} · exact model plus per-task thinking required only for roles with no policy; neither uses an ambient default.`,
    ...(effective.intensity === "orchestrator"
      ? ["Delegate all transferable work; main agent keeps final acceptance."]
      : []),
  ];
}

/** Shared with role-mode tool redirection so launch models and thinking stay identical. */
export function advisorRoleLines(state: RuntimeState): string {
  const { effective } = state;
  return validAdvisors(state)
    .map(({ index, setting }) => {
      // Advisor thinking is never configured, so the main agent always chooses it per run.
      const thinking: RoleThinking = { kind: "unset" };
      const label =
        effective.advisors.length === 1 ? "Advisor (optional)" : `Advisor ${index + 1} (optional)`;
      const profile = advisorProfile(setting, state.admissions);
      const extension =
        profile === "anthropic-auth"
          ? "; provider extension explicitly enabled: normal configuration, startup hook and account diagnostic command are trusted host code, not model tools; never invoke the diagnostic automatically"
          : profile === "admitted"
            ? "; provider extension admitted by the user: it runs as trusted host code in the child, not as model tools"
            : "";
      // Reading is a profile, not a launch option: the block must name the profile that actually runs,
      // and say what it implies so the main agent knows it can hand over a path. The line states
      // reading only when that resolved profile is the one that reads, never from the flag alone.
      const agent = advisorAgentNameFor(state, setting, index);
      const reading =
        agent === ADVISOR_READ_AGENT_NAME
          ? "; reading: on, open only the paths the brief names"
          : "";
      return `\n${roleLine(label, setting, thinking, `; agent profile: ${promptString(agent)}${extension}${reading}`)}`;
    })
    .join("");
}

/** The role rules are generated only for the enabled subset; a disabled role never gains a rule. */
function roleRules(enabled: readonly ModelRole[]): string {
  const rules = [roleFitPolicy()];
  if (enabled.includes("small")) rules.push(SMALL_ROLE_POLICY);
  if (enabled.includes("medium")) rules.push(MEDIUM_ROLE_POLICY);
  if (enabled.includes("large")) {
    rules.push(
      enabled.includes("small") && enabled.includes("medium")
        ? LARGE_EXCEPTIONAL_POLICY
        : enabled.includes("small")
          ? LARGE_COVERS_MEDIUM_POLICY
          : LARGE_CAPABLE_POLICY,
    );
  }
  return rules.join("\n");
}

export function buildDelegationPolicy(state: RuntimeState): string | undefined {
  const { effective } = state;
  const advisorEnabled = isAdvisorEnabled(effective) && !hasAdvisorError(state);
  const advisors = advisorEnabled ? validAdvisors(state) : [];
  const advisorRoleLine = advisorEnabled ? advisorRoleLines(state) : "";
  const advisorSection = advisorEnabled
    ? `\n\nAdvisor consultation:\n${advisorPolicy(
        effective.advisorLaunch,
        advisors.length,
        advisors.some(
          ({ setting, index }) => advisorAgentNameFor(state, setting, index) !== ADVISOR_AGENT_NAME,
        ),
      )}`
    : "";
  const advisorTool = effective.advisorLaunch === "tool" && advisorEnabled;
  const correction = state.launchCorrection ?? "correct";

  if (effective.intensity === "off" || hasRuntimeError(state)) {
    if (!advisorRoleLine) return undefined;
    return `<delegation_policy>
<!-- pi-delegation-policy:owned -->
Purpose
Delegation intensity: ${effective.intensity}${hasRuntimeError(state) ? " (unavailable)" : ""}. Advisor: on. Only consultation guidance is active: this policy requests no execution delegation, optional role selection, or ContextShunt. Keep execution with the main agent unless other applicable instructions require otherwise. Host permissions and user restrictions still apply.${advisorSection}

Roles:${advisorRoleLine}

Limits:
${advisorOnlyLimits(advisorTool)} ${LIMITS_RETENTION}
</delegation_policy>`;
  }
  const { enabled, disabled } = rolesByState(effective);
  if (enabled.length === 0) return undefined;

  const intensityPolicy =
    effective.intensity === "normal"
      ? NORMAL_POLICY
      : effective.intensity === "aggressive"
        ? AGGRESSIVE_POLICY
        : ORCHESTRATOR_POLICY;
  const orchestrator = effective.intensity === "orchestrator";
  const ownership = orchestrator ? "" : ` ${LEGACY_OWNERSHIP}`;
  const restrictions = advisorEnabled ? USER_RESTRICTIONS : DELEGATION_RESTRICTIONS;
  // One paragraph and one line per configured entry; an unconfigured family leaves no trace, and an
  // entry whose model is not available is left out because the launch check refuses it.
  const entryKeys = (family: "uiDesign" | "vision") =>
    optionalRoleEntryKeys(family).filter(
      (key) => effective[key] !== undefined && isAdvertisedOptionalEntry(state, key),
    );
  const visualEntries = entryKeys("uiDesign");
  const visionEntries = entryKeys("vision");
  const optionalRules = [
    ...(visualEntries.length
      ? [
          `${VISUAL_DESIGN_POLICY} ${orchestrator ? OPTIONAL_ROLE_ROUTING_ORCHESTRATOR : OPTIONAL_ROLE_ROUTING_LEGACY}`,
        ]
      : []),
    ...(visionEntries.length ? [VISION_POLICY] : []),
  ];
  const optional = optionalRules.length ? `\n\n${optionalRules.join("\n\n")}` : "";
  const roleLines = enabled
    .map((role) =>
      roleLine(roleName(role), effective[role] as ModelRef, roleThinking(effective.thinking[role])),
    )
    .join("\n");
  const optionalRoleLines = [...visualEntries, ...visionEntries]
    .map(
      (key) =>
        `\n${roleLine(ROLE_LABELS[key], effective[key] as ModelRef, roleThinking(effective.thinking[key]))}`,
    )
    .join("");
  // One verified line instead of repeating the fact on every role line, so the choice between a role
  // that sees and one that does not is decidable at a glance and says nothing it cannot prove. It
  // lists every model the configuration holds, including an entry this policy would not launch: the
  // line is a fact about the models, not about one launch.
  const entryKeysOf = (family: "uiDesign" | "vision") =>
    optionalRoleEntryKeys(family).filter((key) => effective[key] !== undefined);
  const capabilityLine = `Model input (as the host registry reports it): ${[
    ...enabled.map((key) => `${ROLE_LABELS[key]} ${capabilityText(state, key)}`),
    ...entryKeysOf("uiDesign").map((key) => `${ROLE_LABELS[key]} ${capabilityText(state, key)}`),
    ...entryKeysOf("vision").map((key) => `${ROLE_LABELS[key]} ${capabilityText(state, key)}`),
    ...(advisorEnabled
      ? effective.advisors.map(
          (_, index) => `Advisor ${index + 1} ${advisorCapabilityText(state, index)}`,
        )
      : []),
  ].join(" · ")}.`;
  // A fact, not a step: with nothing that can open an image, no rule could fix it, and it must be said
  // even when no optional role is configured at all.
  const imageFact = noImageCapableRoleEverywhere(state, advisorEnabled)
    ? `\n\nNo configured role accepts image input, so image work cannot be delegated until you configure Vision with a model that reads images.`
    : "";
  const enabledLine = `Enabled ordinary roles: ${enabled.map(roleName).join(", ")}.${disabled.length ? ` Disabled ordinary roles: ${disabled.map(roleName).join(", ")}.` : ""}`;
  const optionalLine = [...visualEntries, ...visionEntries].length
    ? `Optional roles: ${[...visualEntries, ...visionEntries].map((key) => ROLE_LABELS[key]).join(", ")}.`
    : "";

  return `<delegation_policy>
<!-- pi-delegation-policy:owned -->
Purpose
${PURPOSE}

Do it yourself?
Intensity: ${effective.intensity}. ${intensityPolicy}${orchestrator ? "" : ` ${TINY_EDIT}`}${ownership} ${restrictions}${advisorSection}

Role selection:
${roleRules(enabled)}
Model preference: ${effective.preference}. ${preferenceGuidance(effective.preference, enabled)}
${capabilityLine}${optional}${imageFact}

Child briefs:
${childBriefPolicy(enabled, [...visualEntries, ...visionEntries], advisorEnabled)}

Launch:
${launchPolicy(correction)}

Roles:
${enabledLine}${optionalLine ? `\n${optionalLine}` : ""}
${roleLines}${optionalRoleLines}${advisorRoleLine}

Results:
${RESULTS_POLICY}${orchestrator ? ORCHESTRATOR_RESULTS : ""}

Limits:
${LIMITS_BOUNDARY[correction]} ${LIMITS_REFUSAL} ${limitsTools(advisorTool)} ${LIMITS_RETENTION}
</delegation_policy>`;
}
